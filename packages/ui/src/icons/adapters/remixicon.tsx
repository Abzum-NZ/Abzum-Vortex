const remixIcon = (Glyph: RemixiconComponentType): ComponentType<VortexIconProps> => {
  function RemixGlyph({ color, ...props }: VortexIconProps) {
    return <Glyph {...props} {...(color === undefined ? {} : { color })} />;
  }
  return RemixGlyph;
};

