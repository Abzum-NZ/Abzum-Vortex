const canonicalLanguageTagSchema = z
  .string()
  .min(2)
  .refine((value) => {
    try {
      return Intl.getCanonicalLocales(value)[0] === value;
    } catch {
      return false;
    }
  }, "Language must be a canonical BCP-47 language tag");

export const organizationRuntimeSettingsSchema = z
  .object({
    organizationId: organizationIdSchema,
    language: canonicalLanguageTagSchema,
    timeZone: z
      .string()
      .min(1)
      .refine(
        (value) => supportedIanaTimeZonesV2026d.has(value),
        "Time zone must be a supported canonical IANA zone",
      ),
    currency: z
      .string()
      .length(3)
      .refine(
        (value) => currentIso4217Alpha3CodeSetV2026_01_01.has(value),
        "Currency must be a current ISO-4217 code",
      ),
    dateFormat: z.enum(organizationRuntimeSettingsDateFormats),
    // Closed serialization of ECMA-402 `useGrouping`; `never` maps to false.
    numberFormat: z.enum(organizationRuntimeSettingsNumberFormats),
    revision: revisionSchema,
  })
  .strict();

/**
 * Steward organisation-account language: the same canonical BCP-47 tag bounded by the
 * organisation-account language constraint (2..35 characters), so a valid long tag is
 * refused as an invalid command instead of failing the account constraint later.
 */
export const organizationAccountLanguageSchema =
  organizationRuntimeSettingsSchema.shape.language.max(35);

export type OrganizationRuntimeSettings = z.infer<typeof organizationRuntimeSettingsSchema>;
