-- `link`) or its `toRecordTypes` list (compiled `link_to_one_of_several`, and
-- every private facts relationship). True only when the concrete record type
-- is one of them.
create function vortex_record.relationship_declares_target_internal(
  p_relationship jsonb,
  p_record_type_id uuid
)
returns boolean
language sql
immutable
security invoker
set search_path = ''
as $function$
  select p_record_type_id is not null and exists (
    select 1
    from pg_catalog.jsonb_array_elements(
      case
        when pg_catalog.jsonb_typeof(p_relationship -> 'toRecordType') = 'object'
          then pg_catalog.jsonb_build_array(p_relationship -> 'toRecordType')
        when pg_catalog.jsonb_typeof(p_relationship -> 'toRecordTypes') = 'array'
          then p_relationship -> 'toRecordTypes'
        else '[]'::jsonb
      end
    ) as target(value)
    where pg_catalog.lower(target.value ->> 'recordTypeId') =
      pg_catalog.lower(p_record_type_id::text)
  )
$function$;

