-- #562: a relationship may use any of its declared target record types.
--
-- A stored edge already names its concrete target: `to_storage_contract_id`
-- is the exact storage contract of the target record type the writer resolved
-- from the link value, and both edge writers refuse a type outside the
-- relationship's provisioned `target_record_type_ids`. What remained singular
-- was every reader and caller above the writers. They accepted only a
-- relationship declaring one `toRecordType` and refused, omitted or skipped a
-- `link_to_one_of_several` relationship declaring `toRecordTypes`:
--
-- * save: `save_base_record`, `save_named_action_set_fields_internal` and the
--   named-action creation plan refused the field outright;
-- * reads and permissions: the three facts loaders
--   (`load_record_access_facts_internal`, its named-action clone
--   `load_named_action_facts_internal` generated by 20260915010000, and the
--   ownership-transfer twin) omitted the relationship, so Access routes and
--   inherited ownership through it always refused;
-- * totals: total dependency resolution, the dependency-closure walk, the four
--   locked total preparations, the two save preflights and the named-action
--   link-target walk required or filtered on the single target;
-- * delete and restore: the lifecycle total-closure seed and the restore
--   invariant compared against the single target.
--
-- This migration gives every one of them the same rule. A relationship's
-- declared targets are its single `toRecordType` or its `toRecordTypes` list;
-- the concrete target is always the one the edge or link value actually
-- names, and it is accepted only when it is a member of that declared set.
-- `vortex_record.relationship_declares_target_internal` is that one
-- membership test for every Record caller. The private facts representation
-- carries one uniform `toRecordTypes` list on every relationship, and Access
-- proves the concrete stored target record's own type a member of it before
-- matching the edge witness against exactly that type.
--
-- The shared facts shape, its closed validator and every current producer and
-- consumer change together, so no singular compatibility path remains. The
-- edge table and its writers are unchanged; no stored data changes. #561's
-- relationship edge lock order is untouched: the link-target walk now includes
-- polymorphic links in the same canonical order, so their targets are locked
-- before edges exactly as single-target links are.
--
-- Every function below is patched in place from its current definition, as
-- `20260923220000_unify_relationship_edge_lock_order.sql` does: each reviewed
-- source fragment must occur exactly once, or the migration aborts rather than
-- silently skipping a caller.

